"""Stage 10: publish/ folder: FINAL.mp4, cover, 04-publish-package.md (template from productions/_templates)."""
import json
import shutil
from pathlib import Path

from . import config, ff
from .state import Production, now


def _mmss(t):
    if t is None:
        return "__:__.__"
    if isinstance(t, str):
        return t
    m, s = divmod(float(t), 60)
    return f"{int(m)}:{s:05.2f}"


def package(prod: Production, version, log=print):
    build, pub = prod.d("build"), prod.d("publish")
    res = json.loads((build / f"edl.v{version}.resolved.json").read_text())
    rights = res["audio_rights"]
    variant = "clean" if rights == "in_app_library" else "final"
    qc = json.loads((build / f"qc_v{version}_{variant}.json").read_text())
    src = Path(qc["file"])
    final = pub / "FINAL.mp4"
    shutil.copy2(src, final)
    info = ff.media_info(final)
    ld = qc["loudness"]
    cap = res.get("caption") or {}
    audio = cap.get("audio") or {}

    # cover: frame at cover_at (or the D marker / 40% point), full res + 3:4 grid preview
    t = res.get("cover_at")
    if t is None:
        t = res["markers"].get("D", res["total"] * 0.4)
    ff.frame_at(final, t, pub / "cover.jpg", vf="scale=1080:1920")
    ff.frame_at(final, t, pub / "cover_grid_preview_3x4.jpg", vf="crop=1080:1440:0:240,scale=540:-2")

    tags = [h if h.startswith("#") else f"#{h}" for h in cap.get("hashtags", [])][:5]
    d_time = res["markers"].get("D")
    tamil = [x["text"] for x in res["text"] if x.get("needs_check")]
    warns = [c for c in qc["checks"] if c["status"] in ("warn", "fail")]
    fails = [c for c in qc["checks"] if c["status"] == "fail"]
    lines = [
        f"# Publish Package — {prod.id} · {cap.get('title', prod.root.name)}", "",
        f"> Generated by reel-engine on {now()} from `build/edl.v{version}.json` · Rules in "
        f"[28](../../../28-reels-export-and-publishing.md) · Autonomous Mode ([26](../../../26-video-production-workflow.md))",
        f"> QC verdict: **{qc['verdict'].upper()}** (`build/qc_v{version}_{variant}.md`). Your review on the phone is the final gate.",
        "", "## 1. Files", "| File | Purpose | Measured |", "|---|---|---|",
        f"| `publish/FINAL.mp4` | Upload this | {info['width']}×{info['height']} · {info['fps']} fps · {info['duration']:.2f} s · "
        f"{ld['integrated_lufs']} LUFS · TP {ld['true_peak_dbtp']} dBTP |",
        "| `publish/cover.jpg` | Custom cover (check the 3:4 grid preview) | `cover_grid_preview_3x4.jpg` |",
    ]
    sg = prod.root / "renders" / f"v{version}_syncguide.mp4"
    if sg.exists():
        lines.append(f"| `renders/{sg.name}` | Timing review only: **never upload** (contains reference audio) | — |")
    lines += ["", "## 2. Audio"]
    if rights == "in_app_library":
        lines += ["| Item | Value |", "|---|---|",
                  f"| Track (exact Instagram name) | {audio.get('name', '__ (see 02-audio-options.md)')} |",
                  f"| Start point in track | {_mmss(audio.get('start'))} = video 0.00 s |",
                  f"| Volume: original audio / music | {audio.get('volume', '80% / 70%')} |",
                  f"| Sync check | {'Drop (D) must hit video ' + format(d_time, '.2f') + ' s' if d_time is not None else 'no drop marker'}"
                  f"{' (' + audio['sync_note'] + ')' if audio.get('sync_note') else ''} |",
                  f"| Popularity / usage count | {audio.get('evidence', 'UNVERIFIED: needs an audio-page screenshot (KB 22 §5)')} |",
                  "", "FINAL.mp4 has natural sound + SFX only (≈ −16 LUFS). Add the track in Instagram or Edits "
                  "(KB 28 §3); film audio is never baked into the file (KB 15 §6)."]
    else:
        lines += [f"Music is baked into FINAL.mp4 (rights path: `{rights}`; licence proof in `licenses/`). "
                  "It will appear as original audio on Instagram."]
    lines += ["", "## 3. Caption", "```", cap.get("text", "<hook line + keyword>\n<context>\n<CTA>"),
              *([f"🎵 {audio['credit']}"] if audio.get("credit") else []), " ".join(tags), "```",
              "", "## 4. Settings",
              f"- Trial Reel: {cap.get('trial', 'no')}", "- Auto-captions: ON",
              f"- Keywords: {', '.join(cap.get('keywords', [])) or '—'}", "- Labels (AI / paid partnership): none",
              "", "## 5. Final QC",
              f"- [{'x' if not fails else ' '}] Technical checks (reel-engine QC v{version}: {qc['verdict']})",
              "- [ ] Watched on the phone (sound + muted)",
              "- [ ] Audio sync confirmed in-app" if rights == "in_app_library" else "- [x] Audio baked in",
              f"- [ ] Text proofread{': **Tamil text to check: ' + ', '.join(tamil) + '**' if tamil else ''}",
              "- [ ] Safety and cultural check"]
    if warns:
        lines += ["", "### QC notes (known compromises / things to look at)"]
        lines += [f"- **{c['status']}** {c['area']}: {c['detail']}" for c in warns]
    lines += ["", "## 6. After posting", "- Posted on: · Link:", "- 72 h Insights → audit file:"]
    (pub / "04-publish-package.md").write_text("\n".join(lines) + "\n")
    prod.mark("delivered", version=version, final=str(final.relative_to(prod.root)), verdict=qc["verdict"])
    log(f"  delivered {final.relative_to(config.KB) if config.KB in final.parents else final}")
    return final
